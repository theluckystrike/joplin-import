import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { jexBytes } from '../src/vector';
import { planImport } from '../src/convert';
import { readJex } from '../src/joplin';
import { auditArchives, auditMarkdown } from '../src/audit';
import { demoMembers } from './sample';

const files: [string, boolean][] = [['Joplin export.jex', false], ['Joplin export later.jex', true]];
const dirs = ['docs/sample-notes', 'test/e2e/vault/Joplin Export Import'];

describe('demo archives', () => {
	if (process.env.WRITE_SAMPLE === '1') for (const d of dirs) for (const [name, later] of files) writeFileSync(`${d}/${name}`, jexBytes(demoMembers(later)));
	for (const d of dirs) for (const [name, later] of files) {
		it(`${d}/${name} equals the generated bytes`, () => {
			expect(existsSync(`${d}/${name}`)).toBe(true);
			expect(new Uint8Array(readFileSync(`${d}/${name}`))).toEqual(jexBytes(demoMembers(later)));
		});
	}

	it('gives the counts and the report that the README and qa.json describe', () => {
		const plan = planImport(readJex(jexBytes(demoMembers())), 'Joplin import', () => false);
		expect(plan.counts).toEqual({ notes: 5, notebooks: 3, tags: 2, resources: 2 });
		expect(plan.notes.map((n) => n.path)).toEqual([
			'Joplin import/Work/Q3 plan--4d5e6f70819243a4a526d7e8f90a1b23.md',
			'Joplin import/Work/Meetings/Weekly standup--5e6f7081920344b5b637e8f90a1b2c34.md',
			'Joplin import/Personal/Lisbon trip--6f708192a31445c6c748f90a1b2c3d45.md',
			'Joplin import/Personal/Budget--8192a3b4c53647e8e96a1b2c3d4e5f67.md',
		]);
		expect(plan.attachments.map((a) => a.path)).toEqual(['Joplin import/_resources/92a3b4c5d64758f9fa7b2c3d4e5f6078.png']);
		expect(plan.report.missingResources.length).toBe(1);
		expect(plan.report.unsupported.length).toBe(1);
		expect(plan.report.tags).toEqual(['Tag "travel plans" is written as "travel-plans".']);
	});

	it('gives the audit row and the changed notes that the end-to-end test expects', () => {
		const a = readJex(jexBytes(demoMembers()));
		const b = readJex(jexBytes(demoMembers(true)));
		const text = auditMarkdown(auditArchives([{ name: 'Joplin Export Import/Joplin export.jex', archive: a }, { name: 'later.jex', archive: b }]), 'x');
		expect(text).toContain('| Joplin Export Import/Joplin export.jex | 5 | 1 | 3 | 2 | 4 | 0 | 1 | 0 |');
		const p1 = planImport(a, 'X', () => false);
		const p2 = planImport(b, 'X', () => false);
		expect(p2.notes.filter((n, i) => n.text !== p1.notes[i]!.text).map((n) => n.path.split('/').pop())).toEqual(['Q3 plan--4d5e6f70819243a4a526d7e8f90a1b23.md', 'Weekly standup--5e6f7081920344b5b637e8f90a1b2c34.md']);
	});
});
